/** Monta a galeria repetindo um conjunto de títulos/descrições genéricos por tipo de produto */
function construirGaleria(
  imagens: string[],
  variantes: { titulo: string; descricao: string }[],
): FotoGaleria[] {
  return imagens.map((imagem, i) => ({ imagem, ...variantes[i % variantes.length]! }));
}

